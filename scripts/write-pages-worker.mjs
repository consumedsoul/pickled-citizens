import fs from 'node:fs/promises';
import path from 'node:path';

/**
 * Collect every file under `public/` as a site-root path (e.g. `/llms.txt`,
 * `/images/logo.png`).
 *
 * The Pages worker needs an explicit list: with a `_worker.js` present and no
 * `_routes.json`, Cloudflare Pages routes EVERY request to the worker, so any
 * path the worker does not hand to the ASSETS binding falls through to
 * OpenNext and gets Next's 404 page. A hardcoded prefix list silently drops
 * new public/ files (this is how /llms.txt and /robots.txt started 404ing),
 * so derive the list from the directory itself.
 */
export async function collectPublicPaths(dir, prefix = '') {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const paths = [];

  for (const entry of entries) {
    // Ignore macOS/editor cruft that should never be served.
    if (entry.name === '.DS_Store') continue;

    const routePath = `${prefix}/${entry.name}`;
    if (entry.isDirectory()) {
      paths.push(...(await collectPublicPaths(path.join(dir, entry.name), routePath)));
    } else if (entry.isFile()) {
      paths.push(routePath);
    }
  }

  return paths.sort();
}

export function buildWorkerCode(assetPaths) {
  return `import opennext from "./opennext-worker.js";

// Every file in public/ at build time, plus Next's build output. Generated by
// scripts/write-pages-worker.mjs — do not edit by hand.
const PUBLIC_ASSETS = new Set(${JSON.stringify(assetPaths)});

function isAssetPath(pathname) {
  return (
    pathname.startsWith("/_next/") ||
    pathname === "/favicon.ico" ||
    PUBLIC_ASSETS.has(pathname)
  );
}

export default {
  async fetch(request, env, ctx) {
    const url = new URL(request.url);

    // Serve static assets directly from the Pages asset binding. Without this
    // every request (including public/ files) goes to the OpenNext worker,
    // which does not know about them and returns Next's 404 page.
    if (isAssetPath(url.pathname)) {
      const assetResp = await env.ASSETS.fetch(request);
      if (assetResp.status !== 404) return assetResp;
    }

    return opennext.fetch(request, env, ctx);
  },
};
`;
}

const isMain = process.argv[1] && import.meta.url === `file://${path.resolve(process.argv[1])}`;

if (isMain) {
  const assetPaths = await collectPublicPaths('public');
  await fs.writeFile('.open-next/pages/_worker.js', buildWorkerCode(assetPaths), 'utf8');
  console.log(`write-pages-worker: ${assetPaths.length} public asset(s) routed to ASSETS`);
}
